/**
 * Seed data for the public demo — an India-first gig board: Mumbai, Bengaluru,
 * Delhi, Goa, Pune and Kolkata. Dates are anchored to the day the site was
 * built (NEXT_PUBLIC_BUILD_DAY) so the board always looks current.
 */

export const BUILD_DAY = process.env.NEXT_PUBLIC_BUILD_DAY || new Date().toISOString().slice(0, 10);

/** ISO date `n` days after the build day. */
export function day(n: number): string {
  const d = new Date(`${BUILD_DAY}T12:00:00`);
  d.setDate(d.getDate() + n);
  return d.toISOString().slice(0, 10);
}

